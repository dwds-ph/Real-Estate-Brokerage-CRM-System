function renderDeedOfAbsoluteSale(doc: Doc, data: ContractData): void {
  let y = MARGIN + 15;

  doc.setFontSize(FONT_SIZE_TITLE);
  doc.setFont("helvetica", "bold");
  doc.text("DEED OF ABSOLUTE SALE", PAGE_WIDTH / 2, y, { align: "center" });
  y += LINE_HEIGHT + 5;

  // Parties
  y = addSection(
    doc,
    "KNOW ALL MEN BY THESE PRESENTS:",
    [`This DEED OF ABSOLUTE SALE made and executed by and between:`],
    y,
  );
  y = addField(doc, "SELLER", data.sellerName, y);
  if (data.sellerAddress)
    {y = addField(doc, "Seller Address", data.sellerAddress, y);}
  y = addField(doc, "BUYER", data.buyerName, y);
  if (data.buyerAddress)
    {y = addField(doc, "Buyer Address", data.buyerAddress, y);}
  y += 3;

  // Recitals
  const recitals = [
    "WITNESSETH: That the SELLER is the absolute owner of the property described below;",
    "That the SELLER desires to sell the property to the BUYER;",
    "That the BUYER desires to purchase the property upon the terms and conditions set forth herein.",
  ];
  y = addSection(doc, "RECITALS", recitals, y);
  y += 3;

  // Property
  y = addSection(doc, "PROPERTY DESCRIPTION", [], y);
  y = addField(doc, "Property", data.propertyTitle, y);
  y = addField(
    doc,
    "Address",
    `${data.propertyAddress}, ${data.propertyCity}${data.propertyProvince ? `, ${data.propertyProvince}` : ""}`,
    y,
  );
  if (data.tctNumber) {y = addField(doc, "TCT No.", data.tctNumber, y);}
  if (data.lotArea) {y = addField(doc, "Lot Area", `${data.lotArea} sqm`, y);}
  if (data.floorArea)
    {y = addField(doc, "Floor Area", `${data.floorArea} sqm`, y);}
  y += 3;

  // Sale
  y = addSection(
    doc,
    "SALE AND TRANSFER",
    [
      `For and in consideration of the sum of ${formatCurrency(data.purchasePrice)} (the "Purchase Price"), the SELLER hereby sells, transfers, and conveys the property to the BUYER.`,
      "The SELLER warrants that the property is free from all liens and encumbrances.",
    ],
    y,
  );
  y += 3;

  // Tax computation
  const cgt = data.purchasePrice * 0.06;
  const dst = data.purchasePrice * 0.015;
  const taxInfo = [
    `Capital Gains Tax (CGT) — 6%: ${formatCurrency(cgt)}`,
    `Documentary Stamp Tax (DST) — 1.5%: ${formatCurrency(dst)}`,
    "The SELLER shall be responsible for the CGT. The BUYER shall be responsible for the DST.",
    "Transfer tax and registration fees shall be for the account of the BUYER.",
  ];
  y = addSection(doc, "TAXES AND FEES", taxInfo, y);
  y += 3;

  // Notarial acknowledgment block
  y = addSection(
    doc,
    "ACKNOWLEDGMENT",
    [
      `SIGNED this ${data.dateOfAgreement} in ${data.propertyCity || "________"}, Philippines.`,
    ],
    y,
  );
  y += 3;

  y = addSignatures(doc, data, y);

  // Notary block
  y += 5;
  if (y > 260) {
    doc.addPage();
    y = MARGIN + 10;
  }
  const notaryBlock = [
    "REPUBLIC OF THE PHILIPPINES )",
    `${data.propertyCity || "CITY OF ________"} ) S.S.`,
    "",
    "BEFORE ME, a Notary Public for and in the above jurisdiction, personally appeared:",
    `${data.sellerName} (Seller) — bearing valid government-issued identification,`,
    `${data.buyerName} (Buyer) — bearing valid government-issued identification,`,
    "known to me and to me known to be the same persons who executed the foregoing instrument.",
    "WITNESS MY HAND AND SEAL on the date and place first above written.",
    "",
    "_________________________________",
    "NOTARY PUBLIC",
    "Doc. No. _____; Page No. _____; Book No. _____; Series of _____.",
  ];
  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "normal");
  for (const line of notaryBlock) {
    if (y > 285) {
      doc.addPage();
      y = MARGIN + 10;
    }
    doc.text(line, MARGIN, y);
    y += line ? LINE_HEIGHT : 3;
  }
}

function renderLetterOfIntent(doc: Doc, data: ContractData): void {
  let y = MARGIN + 15;

  doc.setFontSize(FONT_SIZE_TITLE);
  doc.setFont("helvetica", "bold");
  doc.text("LETTER OF INTENT", PAGE_WIDTH / 2, y, { align: "center" });
  y += LINE_HEIGHT + 5;

  const lines = [
    data.dateOfAgreement,
    "",
    `${data.sellerName || "Property Owner"}`,
    `${data.propertyAddress || ""}`,
    `${data.propertyCity || ""}`,
    "",
    `Dear ${data.sellerName || "Property Owner"},`,
    "",
    `This letter expresses our client's interest in purchasing the property described as "${data.propertyTitle}" located at ${data.propertyAddress}, ${data.propertyCity}${data.propertyProvince ? `, ${data.propertyProvince}` : ""}.`,
    "",
    `Proposed Purchase Price: ${formatCurrency(data.purchasePrice)}`,
    data.paymentTerms ? `Proposed Payment Terms: ${data.paymentTerms}` : "",
    "",
    "This Letter of Intent is non-binding and is subject to the execution of a formal Contract to Sell or Deed of Absolute Sale.",
    "",
    "We look forward to your favorable response.",
    "",
    "Very truly yours,",
    "",
    "",
    `${data.buyerName}`,
    `Through: ${data.brokerName}`,
  ];

  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "normal");
  for (const line of lines) {
    if (!line) {
      y += 3;
      continue;
    }
    if (y > 280) {
      doc.addPage();
      y = MARGIN + 10;
    }
    doc.text(line, MARGIN, y);
    y += LINE_HEIGHT;
  }
}

function renderBrokerEngagement(doc: Doc, data: ContractData): void {
  let y = MARGIN + 15;

  doc.setFontSize(FONT_SIZE_TITLE);
  doc.setFont("helvetica", "bold");
  doc.text("BROKER ENGAGEMENT LETTER", PAGE_WIDTH / 2, y, { align: "center" });
  y += LINE_HEIGHT + 5;

  const lines = [
    data.dateOfAgreement,
    "",
    `${data.buyerName}`,
    `${data.buyerAddress || ""}`,
    "",
    `Dear ${data.buyerName},`,
    "",
    `We are pleased to confirm our engagement as your exclusive real estate broker/agent for the acquisition of the below-described property.`,
    "",
    `Property: ${data.propertyTitle}`,
    `Location: ${data.propertyAddress}, ${data.propertyCity}${data.propertyProvince ? `, ${data.propertyProvince}` : ""}`,
    "",
    "SCOPE OF SERVICES:",
    "1. Property search and identification",
    "2. Negotiation assistance",
    "3. Documentation and compliance",
    "4. Coordination with lenders and government agencies",
    "5. End-to-end transaction management",
    "",
    data.commissionRate
      ? `Commission: ${data.commissionRate}% of the purchase price or as separately agreed.`
      : "Commission: As mutually agreed upon in a separate agreement.",
    "",
    "This engagement shall be governed by the provisions of Republic Act No. 9646 (Real Estate Service Act).",
    "",
    "Please signify your agreement by signing below.",
    "",
    "Sincerely,",
    "",
    "",
    `${data.brokerName}`,
    data.brokerAgency ? data.brokerAgency : "",
    data.brokerLicense ? `License No.: ${data.brokerLicense}` : "",
  ];

  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "normal");
  for (const line of lines) {
    if (!line) {
      y += 3;
      continue;
    }
    if (y > 280) {
      doc.addPage();
      y = MARGIN + 10;
    }
    doc.text(line, MARGIN, y);
    y += LINE_HEIGHT;
  }

  y += 5;
  addSignatures(doc, data, y);
}

// ─── Shared ─────────────────────────────────────────────────────────

function addSignatures(doc: Doc, data: ContractData, y: number): number {
  if (y > 250) {
    doc.addPage();
    y = MARGIN + 10;
  }

  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "bold");
  doc.text("SIGNATURES", MARGIN, y);
  y += LINE_HEIGHT + 4;
  doc.setFont("helvetica", "normal");

  // Seller
  doc.text("_________________________________", MARGIN, y);
  y += LINE_HEIGHT;
  doc.text(data.sellerSignatory || data.sellerName, MARGIN, y);
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text("(SELLER)", MARGIN + 80, y);
  doc.setTextColor(0);
  y += LINE_HEIGHT + 5;

  // Buyer
  doc.setFontSize(FONT_SIZE_BODY);
  doc.text("_________________________________", MARGIN, y);
  y += LINE_HEIGHT;
  doc.text(data.buyerSignatory || data.buyerName, MARGIN, y);
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text("(BUYER)", MARGIN + 80, y);
  doc.setTextColor(0);
  y += LINE_HEIGHT + 5;

  // Witness 1
  doc.setFontSize(FONT_SIZE_BODY);
  doc.text("_________________________________", MARGIN, y);
  y += LINE_HEIGHT;
  doc.text(data.witness1 || "________________________", MARGIN, y);
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text("(WITNESS)", MARGIN + 80, y);
  doc.setTextColor(0);
  y += LINE_HEIGHT + 5;

  // Witness 2
  doc.setFontSize(FONT_SIZE_BODY);
  doc.text("_________________________________", MARGIN, y);
  y += LINE_HEIGHT;
  doc.text(data.witness2 || "________________________", MARGIN, y);
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text("(WITNESS)", MARGIN + 80, y);
  doc.setTextColor(0);
  y += LINE_HEIGHT + 5;

  return y;
}

// ─── Main Entry Point ──────────────────────────────────────────────

export function generateContract(
  templateId: ContractTemplateId,
  data: ContractData,
): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  addHeader(doc);

  switch (templateId) {
    case "reservation-agreement":
      renderReservationAgreement(doc, data);
      break;
    case "contract-to-sell":
      renderContractToSell(doc, data);
      break;
    case "deed-of-absolute-sale":
      renderDeedOfAbsoluteSale(doc, data);
      break;
    case "letter-of-intent":
      renderLetterOfIntent(doc, data);
      break;
    case "broker-engagement":
      renderBrokerEngagement(doc, data);
      break;
  }

  addFooter(doc);

  return doc;
}

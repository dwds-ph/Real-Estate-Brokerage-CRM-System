import { jsPDF } from "jspdf";
import "jspdf-autotable";
import { type ContractTemplateId, type ContractData } from "./templates";
import { formatCurrency } from "@/lib/utils";

type Doc = jsPDF;

const PAGE_WIDTH = 210; // A4 mm
const MARGIN = 20;
const CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN;
const FONT_SIZE_BODY = 10;
const FONT_SIZE_TITLE = 16;
const FONT_SIZE_SUBTITLE = 12;
const LINE_HEIGHT = 5;

// ─── Helpers ────────────────────────────────────────────────────────

function addHeader(doc: Doc) {
  doc.setFontSize(8);
  doc.setTextColor(100);
  doc.text("Generated by Real Estate Brokerage CRM", MARGIN, 10);
  doc.text(
    new Date().toLocaleDateString("en-PH", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
    PAGE_WIDTH - MARGIN,
    10,
    { align: "right" },
  );
  doc.setDrawColor(200);
  doc.line(MARGIN, 13, PAGE_WIDTH - MARGIN, 13);
  doc.setTextColor(0);
}

function addFooter(doc: Doc) {
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`Page ${i} of ${pageCount}`, PAGE_WIDTH - MARGIN, 295, {
      align: "right",
    });
    doc.setDrawColor(200);
    doc.line(MARGIN, 290, PAGE_WIDTH - MARGIN, 290);
  }
  doc.setTextColor(0);
}

function addSection(
  doc: Doc,
  title: string,
  content: string[],
  y: number,
): number {
  let cursorY = y;

  // Section title
  doc.setFontSize(FONT_SIZE_SUBTITLE);
  doc.setFont("helvetica", "bold");
  doc.text(title, MARGIN, cursorY);
  cursorY += LINE_HEIGHT + 2;

  // Section content
  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "normal");

  for (const line of content) {
    const lines = doc.splitTextToSize(line, CONTENT_WIDTH);
    for (const l of lines) {
      if (cursorY > 275) {
        doc.addPage();
        cursorY = MARGIN + 10;
      }
      doc.text(l, MARGIN, cursorY);
      cursorY += LINE_HEIGHT;
    }
  }

  return cursorY + 3;
}

function addField(
  doc: Doc,
  label: string,
  value: string | number | undefined | null,
  y: number,
): number {
  let cursorY = y;
  if (cursorY > 275) {
    doc.addPage();
    cursorY = MARGIN + 10;
  }
  doc.setFontSize(FONT_SIZE_BODY);
  doc.setFont("helvetica", "bold");
  const displayValue =
    value != null /* eslint-disable-line eqeqeq */ ? String(value) : "________________________";
  doc.text(`${label}: `, MARGIN, cursorY);
  const labelWidth = doc.getTextWidth(`${label}: `);
  doc.setFont("helvetica", "normal");
  doc.text(displayValue, MARGIN + labelWidth, cursorY);
  cursorY += LINE_HEIGHT + 1;
  return cursorY;
}

// ─── Renderers ──────────────────────────────────────────────────────

function renderReservationAgreement(doc: Doc, data: ContractData): void {
  let y = MARGIN + 15;

  // Title
  doc.setFontSize(FONT_SIZE_TITLE);
  doc.setFont("helvetica", "bold");
  doc.text("RESERVATION AGREEMENT", PAGE_WIDTH / 2, y, { align: "center" });
  y += LINE_HEIGHT + 5;

  // Party information
  y = addSection(doc, "PARTIES", [], y);
  y = addField(doc, "SELLER", data.sellerName, y);
  if (data.sellerAddress)
    {y = addField(doc, "Seller Address", data.sellerAddress, y);}
  y = addField(doc, "BUYER", data.buyerName, y);
  if (data.buyerAddress)
    {y = addField(doc, "Buyer Address", data.buyerAddress, y);}
  y = addField(doc, "Broker/Agent", data.brokerName, y);
  if (data.brokerLicense)
    {y = addField(doc, "License No.", data.brokerLicense, y);}
  if (data.brokerAgency) {y = addField(doc, "Agency", data.brokerAgency, y);}
  y += 3;

  // Property
  y = addSection(doc, "PROPERTY", [], y);
  y = addField(doc, "Property", data.propertyTitle, y);
  y = addField(
    doc,
    "Address",
    `${data.propertyAddress}, ${data.propertyCity}${data.propertyProvince ? `, ${data.propertyProvince}` : ""}`,
    y,
  );
  y = addField(doc, "Type", data.propertyType, y);
  if (data.lotArea) {y = addField(doc, "Lot Area", `${data.lotArea} sqm`, y);}
  if (data.floorArea)
    {y = addField(doc, "Floor Area", `${data.floorArea} sqm`, y);}
  if (data.tctNumber) {y = addField(doc, "TCT No.", data.tctNumber, y);}
  y += 3;

  // Financial Terms
  y = addSection(doc, "FINANCIAL TERMS", [], y);
  y = addField(doc, "Purchase Price", formatCurrency(data.purchasePrice), y);
  if (data.reservationFee)
    {y = addField(
      doc,
      "Reservation Fee",
      formatCurrency(data.reservationFee),
      y,
    );}
  y = addField(doc, "Date of Agreement", data.dateOfAgreement, y);
  if (data.targetClosingDate)
    {y = addField(doc, "Target Closing", data.targetClosingDate, y);}
  y += 3;

  // Terms and conditions
  const terms = [
    "1. The BUYER hereby reserves the above-described property through the payment of the reservation fee.",
    "2. The reservation fee is NON-REFUNDABLE but shall be applied as part of the down payment should the BUYER proceed with the purchase.",
    "3. This Agreement shall be governed by and construed in accordance with the laws of the Republic of the Philippines.",
    "4. The SELLER warrants that they have the legal capacity and authority to sell the property.",
    `5. The BROKER, ${data.brokerName}, acts as a duly licensed real estate service practitioner under Republic Act No. 9646 (Real Estate Service Act).`,
    "6. Should the BUYER fail to execute the Contract to Sell within the period agreed upon, this Reservation Agreement shall be deemed cancelled and the reservation fee forfeited.",
    "7. Any amendment to this Agreement shall be in writing and signed by all parties.",
  ];
  y = addSection(doc, "TERMS AND CONDITIONS", terms, y);
  y += 3;

  // RA 9646 Disclosure
  const ra9646 = [
    "DISCLOSURE PURSUANT TO REPUBLIC ACT NO. 9646:",
    "The Real Estate Service Act governs the practice of real estate service in the Philippines.",
    "The broker/agent named herein is duly accredited and holds a valid PRC license.",
    "Any questions or complaints regarding this transaction may be directed to the Professional Regulation Commission (PRC) or the Department of Human Settlements and Urban Development (DHSUD).",
  ];
  y = addSection(doc, "STATUTORY DISCLOSURE", ra9646, y);
  y += 3;

  // Signatures
  addSignatures(doc, data, y);
}

